def read_json(path, default=None):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return default


def atomic_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".new")
    with temporary.open("w") as f:
        os.fchmod(f.fileno(), 0o600)
        json.dump(value, f, ensure_ascii=False, indent=2)
        f.flush()
        os.fsync(f.fileno())
    temporary.replace(path)


def text_secret(path, size=32):
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(secrets.token_hex(size))
        path.chmod(0o600)
    return path.read_text().strip()


def initial_dashboard_password():
    path = STATE / "manager/astrbot-initial-password"
    value = text_secret(path, 20)
    # AstrBot requires uppercase, lowercase and a digit. Also repair only the
    # exact 40-hex value generated by earlier prototype builds, preserving its
    # entropy and any already valid/custom initial credential.
    if re.fullmatch(r"[0-9a-f]{40}", value):
        value = "Aa7!" + value
        temporary = path.with_suffix(".new")
        with temporary.open("w") as stream:
            os.fchmod(stream.fileno(), 0o600)
            stream.write(value)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
    return value


def redact(text):
    text = re.sub(r"(?i)(Bearer\s+)[A-Za-z0-9._~+/-]+", r"\1[redacted]", text)
    text = re.sub(r"\bsk-[A-Za-z0-9_-]{12,}\b", "[redacted]", text)
    return re.sub(r'(?i)([\"\']?(?:api[_-]?key|access[_-]?token|password|authorization)[\"\']?\s*[:=]\s*[\"\']?)[^\s,}\"\']+', r"\1[redacted]", text)


def listening(port):
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=0.15):
            return True
    except OSError:
        return False


